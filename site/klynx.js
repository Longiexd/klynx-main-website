async function handleSubmit(e) {
  e.preventDefault();
  const form = e.target;
  const data = new FormData(form);

  try {
    const response = await fetch(form.action, {
      method: 'POST',
      body: data
    });

    if (!response.ok) {
      const errorText = await response.text();
      console.error('Error response:', errorText);
      let detail = errorText;
      try {
        const parsed = JSON.parse(errorText);
        if (parsed && typeof parsed.error === 'string') {
          detail = parsed.error;
        }
      } catch (_) {
        /* keep raw body */
      }
throw new Error(`${response.status}: ${detail}`);
    }
    
    const result = await response.json();

    if (result.success) {
      form.style.display = 'none';
      document.getElementById('success').style.display = 'block';
    } else {
      console.error('Form submission failed:', result);
      alert(`Error: ${result.error || 'Something went wrong. Please try again.'}`);
    }
  } catch(err) {
    console.error('Submission error:', err);
alert(`Network error: ${err.message}. Please check your connection and try again.`);
  }
}

async function handleReviewSubmit(e) {
  e.preventDefault();
  const form = e.target;
  const errorEl = document.getElementById('review-error');
  errorEl.style.display = 'none';

  // Honeypot — if a bot filled the hidden field, silently pretend success
  if (form.website.value) {
    form.style.display = 'none';
    document.getElementById('review-success').style.display = 'block';
    return;
  }

  const payload = {
    name: form['reviewer-name'].value.trim(),
    company: form['reviewer-company'].value.trim(),
    rating: Number(form.rating.value),
    text: form['review-text'].value.trim()
  };

  const submitBtn = form.querySelector('.review-form-submit');
  const originalLabel = submitBtn.textContent;
  submitBtn.disabled = true;
  submitBtn.textContent = '...';

  try {
    const response = await fetch(`${REVIEWS_API}/submit`, {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify(payload)
    });
    const result = await response.json().catch(() => ({}));
    if (!response.ok || !result.success) {
      throw new Error(result.error || `Request failed (${response.status})`);
    }
    form.style.display = 'none';
    document.getElementById('review-success').style.display = 'block';
  } catch (err) {
    console.error('Review submission error:', err);
    errorEl.textContent = (i18n[currentLang] && i18n[currentLang]['rev.form.error']) || 'Could not submit your review right now. Please try again in a moment.';
    errorEl.style.display = 'block';
    submitBtn.disabled = false;
    submitBtn.textContent = originalLabel;
  }
}

async function loadApprovedReviews() {
  const grid = document.querySelector('.reviews-grid');
  const openSlot = document.querySelector('.review-card.open-slot');
  if (!grid) return;
  try {
    const response = await fetch(`${REVIEWS_API}/approved`);
    if (!response.ok) return;
    const { reviews } = await response.json();
    if (!Array.isArray(reviews) || reviews.length === 0) return;

    reviews.forEach(r => {
      const card = document.createElement('div');
      card.className = 'review-card';
      const initial = (r.name || '?').trim().charAt(0).toUpperCase() || '?';
      const stars = '★'.repeat(Math.max(0, Math.min(5, r.rating || 0)));
      const emptyStars = '☆'.repeat(5 - Math.max(0, Math.min(5, r.rating || 0)));
      card.innerHTML = `
        <div class="review-stars" aria-hidden="true">${stars}${emptyStars}</div>
        <div class="review-body">${escapeHtml(r.text || '')}</div>
        <div class="review-footer">
          <div class="review-avatar g">${escapeHtml(initial)}</div>
          <div>
            <div class="review-name">${escapeHtml(r.name || '')}</div>
            <div class="review-role">${escapeHtml(r.company || '')}</div>
          </div>
        </div>
      `;
      if (openSlot) {
        grid.insertBefore(card, openSlot);
      } else {
        grid.appendChild(card);
      }
    });
  } catch (err) {
    console.error('Could not load reviews:', err);
  }
}

function escapeHtml(str) {
  const div = document.createElement('div');
  div.textContent = str;
  return div.innerHTML;
}


